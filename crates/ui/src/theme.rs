use gpui::{Hsla, rgb};

pub fn background() -> Hsla {
    rgb(0x0e0e0f).into()
}
pub fn foreground() -> Hsla {
    rgb(0xf5f5f5).into()
}
pub fn accent() -> Hsla {
    rgb(0x202022).into()
}
pub fn border() -> Hsla {
    rgb(0x262628).into()
}
pub fn danger() -> Hsla {
    rgb(0xf87171).into()
}
pub fn success() -> Hsla {
    rgb(0x34d399).into()
}
pub fn disabled() -> Hsla {
    rgb(0xaaaaaf).into()
}
